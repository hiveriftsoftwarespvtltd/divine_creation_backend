async function seedLuxuryStationery() {
  console.log('Connecting to MongoDB Atlas...');
  const conn = await mongoose.connect(process.env.MONGO_URI);
  const db = conn.connection.useDb('divine_creations_db');
  const prodsColl = db.db.collection('products');
  const catsColl = db.db.collection('categories');

  console.log(`\nUpserting ${PRODUCTS.length} Luxury Stationery products (Pens, Gift Sets, Accessories, Notebooks)...`);
  let insertedCount = 0;
  let updatedCount = 0;

  for (let i = 0; i < PRODUCTS.length; i++) {
    const item = PRODUCTS[i];

    // Filter by exact title and brand to ensure zero duplicates
    const filter = {
      title: item.title,
      brand: item.brand
    };

    const res = await prodsColl.updateOne(
      filter,
      {
        $set: {
          ...item,
          updatedAt: new Date()
        },
        $setOnInsert: {
          createdAt: new Date()
        }
      },
      { upsert: true }
    );

    if (res.upsertedCount > 0) {
      insertedCount++;
      console.log(`  ✓ [${i + 1}/${PRODUCTS.length}] Inserted: "${item.title}" (${item.brand} - ${item.category})`);
    } else {
      updatedCount++;
      console.log(`  ✓ [${i + 1}/${PRODUCTS.length}] Updated: "${item.title}" (${item.brand} - ${item.category})`);
    }
  }

  // Ensure all 4 categories exist in categories collection
  const categoriesToEnsure = ['Pens', 'Gift Sets', 'Accessories', 'Notebooks'];
  for (const catName of categoriesToEnsure) {
    await catsColl.updateOne(
      { name: catName },
      {
        $set: {
          name: catName,
          image: 'https://placehold.co/500x500',
          featured: true,
          updatedAt: new Date()
        },
        $setOnInsert: {
          createdAt: new Date()
        }
      },
      { upsert: true }
    );
    console.log(`✓ Category "${catName}" verified.`);
  }

  const countsByCategory = {};
  for (const cat of categoriesToEnsure) {
    countsByCategory[cat] = await prodsColl.countDocuments({ category: cat });
  }

  console.log('\n========================================');
  console.log(`SUCCESS: Processed all ${PRODUCTS.length} products.`);
  console.log(`New Inserted: ${insertedCount}, Updated: ${updatedCount}`);
  console.log('Category Counts:', countsByCategory);
  console.log('========================================');

  await mongoose.disconnect();
}

seedLuxuryStationery().catch(err => {
  console.error('Fatal seeding error:', err);
  process.exit(1);
});
